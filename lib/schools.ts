export function schoolKey(name: string): string {
  let s = String(name ?? "").toLowerCase().replace(/\(.*?\)/g, "").replace(/\s+/g, "");
  if (!s) return "";
  s = s.replace(/여자대학교$/, "여대").replace(/대학교$/, "대").replace(/대학$/, "대");
  return ALIAS[s] ?? s;
}
/** 같은 학교인지: 학교 열쇠가 같고, 캠퍼스가 둘 다 있으면 캠퍼스도 같아야 한다. */
export function sameSchool(a: { key: string; campus: string }, b: { key: string; campus: string }) {
  if (!a.key || !b.key || a.key !== b.key) return false;
  return !a.campus || !b.campus || a.campus === b.campus;
}
